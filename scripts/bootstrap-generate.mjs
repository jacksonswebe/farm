/**
 * Generates db/bootstrap.sql — a single file that can be pasted into a
 * browser SQL editor (Neon, Supabase, RDS Query Editor) to stand up a
 * complete environment in one action.
 *
 * Why this exists: the setup has four steps that must happen in order, and
 * the one that matters most — creating a NOBYPASSRLS application role — is
 * the one that fails silently if skipped. Collapsing it to one paste with a
 * self-check at the end removes the chance of a half-configured deployment
 * that looks healthy and has no tenant isolation.
 *
 * Secrets are generated fresh each run and printed once. Re-run for a new set.
 *
 *   node scripts/bootstrap-generate.mjs
 */
import { hash } from '@node-rs/argon2';
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const DEMO_PASSWORD = process.env.DEMO_PASSWORD ?? 'Demo!2345';

const secrets = {
  appPassword: randomBytes(18).toString('base64url'),
  authSecret: randomBytes(32).toString('base64'),
  cronSecret: randomBytes(32).toString('base64'),
  fieldKey: randomBytes(32).toString('hex'),
  demoHash: await hash(DEMO_PASSWORD, { memoryCost: 65536, timeCost: 3, parallelism: 4 }),
};

const schema = readFileSync('db/schema.sql', 'utf8');
const seedRaw = readFileSync('db/seed.sql', 'utf8');

// db/seed.sql is written for psql and uses \set variables plus \-commands,
// neither of which a browser SQL editor understands. Inline the values and
// drop the meta-commands so the result is plain SQL.
const vars = {};
for (const m of seedRaw.matchAll(/^\\set\s+(\w+)\s+'''([^']+)'''/gm)) vars[m[1]] = m[2];

let seed = seedRaw
  .split('\n')
  .filter((line) => !line.trimStart().startsWith('\\'))
  .join('\n');

// Longest names first, so :org_id does not partially match inside another name.
for (const name of Object.keys(vars).sort((a, b) => b.length - a.length)) {
  seed = seed.replaceAll(`:${name}`, `'${vars[name]}'`);
}

const out = `-- =====================================================================
-- SafeSphere EHS — ONE-PASTE BOOTSTRAP
--
-- Paste this entire file into the Neon SQL Editor and press Run. It creates
-- the schema, a demo tenant, working demo passwords, and the least-privilege
-- application role — in the right order, with a self-check at the end.
--
-- Generated by scripts/bootstrap-generate.mjs. The values below are single
-- use: re-run that script for a fresh set.
--
-- ---------------------------------------------------------------------
-- AFTER RUNNING THIS, set four environment variables in Vercel
-- (Project -> Settings -> Environment Variables):
--
--   DATABASE_URL          Your POOLED Neon connection string, edited to use
--                         user  safesphere_app
--                         pass  ${secrets.appPassword}
--
--   AUTH_SECRET           ${secrets.authSecret}
--   CRON_SECRET           ${secrets.cronSecret}
--   FIELD_ENCRYPTION_KEY  ${secrets.fieldKey}
--
-- Then redeploy, and verify with:
--   BASE=https://your-app.vercel.app CRON_SECRET=... bash scripts/preflight.sh
--
-- Demo sign-in: hse@demo.safesphere.app / ${DEMO_PASSWORD}
-- Change or remove the demo users before sharing the URL outside your team.
-- =====================================================================

${schema}

-- =====================================================================
-- Demo tenant
-- =====================================================================
${seed}

-- =====================================================================
-- Working demo passwords
--
-- Precomputed argon2id, because the hash must be produced with the same
-- parameters the application verifies with and a browser SQL editor cannot
-- run argon2.
-- =====================================================================
UPDATE users SET password_hash = '${secrets.demoHash}'
WHERE email LIKE '%@demo.safesphere.app';

-- =====================================================================
-- The least-privilege application role.
--
-- THE STEP THAT MATTERS MOST. Connect the application as the database owner
-- and every row-level security policy above becomes decorative: the app
-- looks completely healthy while tenants can read one another's injury
-- records. The verification block at the end refuses to pass if that is so.
-- =====================================================================
DO $bootstrap$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'safesphere_app') THEN
    EXECUTE 'CREATE ROLE safesphere_app LOGIN NOBYPASSRLS';
  END IF;
END $bootstrap$;

ALTER ROLE safesphere_app WITH PASSWORD '${secrets.appPassword}' NOBYPASSRLS;

GRANT USAGE ON SCHEMA public, app TO safesphere_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO safesphere_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO safesphere_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA app TO safesphere_app;

-- Anything a later migration creates inherits the same grants.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO safesphere_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO safesphere_app;

-- The audit trail is append-only for the application.
REVOKE UPDATE, DELETE ON audit_events FROM safesphere_app;

-- Refreshing a materialized view requires ownership; the scheduled job runs
-- as this role.
ALTER MATERIALIZED VIEW mv_incident_daily OWNER TO safesphere_app;
ALTER MATERIALIZED VIEW mv_action_daily   OWNER TO safesphere_app;

REFRESH MATERIALIZED VIEW mv_incident_daily;
REFRESH MATERIALIZED VIEW mv_action_daily;

-- =====================================================================
-- Self-check. Fails loudly rather than leaving isolation quietly disabled.
-- =====================================================================
DO $verify$
DECLARE
  bypasses    boolean;
  n_incidents integer;
  n_actions   integer;
BEGIN
  SELECT rolbypassrls INTO bypasses FROM pg_roles WHERE rolname = 'safesphere_app';
  IF bypasses THEN
    RAISE EXCEPTION
      'safesphere_app has BYPASSRLS. Tenant isolation would be inert. Do not deploy.';
  END IF;

  SELECT count(*) INTO n_incidents FROM incidents;
  SELECT count(*) INTO n_actions   FROM actions;
  IF n_incidents < 100 THEN
    RAISE EXCEPTION 'Demo data did not load (% events found). Re-run this file.', n_incidents;
  END IF;

  RAISE NOTICE '=========================================================';
  RAISE NOTICE 'SafeSphere bootstrap complete.';
  RAISE NOTICE '  % demo events, % actions loaded', n_incidents, n_actions;
  RAISE NOTICE '  safesphere_app created; NOBYPASSRLS confirmed';
  RAISE NOTICE '  Sign in as hse@demo.safesphere.app / ${DEMO_PASSWORD}';
  RAISE NOTICE '';
  RAISE NOTICE 'Next: set the four environment variables listed at the top';
  RAISE NOTICE 'of this file in Vercel, then redeploy.';
  RAISE NOTICE '=========================================================';
END $verify$;
`;

writeFileSync('db/bootstrap.sql', out);

console.log('Wrote db/bootstrap.sql\n');
console.log('Environment variables for Vercel:');
console.log(`  DB user/password      safesphere_app / ${secrets.appPassword}`);
console.log(`  AUTH_SECRET           ${secrets.authSecret}`);
console.log(`  CRON_SECRET           ${secrets.cronSecret}`);
console.log(`  FIELD_ENCRYPTION_KEY  ${secrets.fieldKey}`);
